import type { AiGatewayRequest, AiProvider } from '../provider.interface.ts';
import type {
  AiAdvisoryResponse,
  AiProviderHealth,
} from '../../../../shared/types/domain.ts';

export class MockAiProvider implements AiProvider {
  readonly id = 'mock' as const;

  async getHealth(): Promise<AiProviderHealth> {
    return {
      providerId: this.id,
      label: 'Mock AI Provider (Tests & Offline Dev)',
      tier: 'mock_test',
      configured: true,
      reachable: true,
      model: 'field-fussion-mock-v1',
      note: 'Deterministic simulated provider for automated tests and zero-cost UI development. Responses are clearly labeled as simulated.',
    };
  }

  async generateAdvisory(request: AiGatewayRequest): Promise<AiAdvisoryResponse> {
    const districtLabel = request.context.district || 'your district';
    const unitLabel = request.context.preferredAreaUnit;

    const advisoryByLang: Record<string, string> = {
      en: `[Simulated Mock Advisory] Based on minimized regional context (${districtLabel}, ${unitLabel}), review local rainfall forecasts before planting and verify soil moisture on site. No official farm records were modified.`,
      lg: `[Okuteesa Okw'okugezesa] Okusinziira ku kitundu kyo (${districtLabel}, ${unitLabel}), kebera embeera y'obudde n'obunnyogovu bw'ettaka nga tonnasiga. Tewali biwandiiko bikuumiddwa bikyusiddwa.`,
      sw: `[Ushauri wa Majaribio] Kulingana na muktadha wa eneo (${districtLabel}, ${unitLabel}), kagua utabiri wa mvua na unyevu wa udongo kabla ya kupanda. Hakuna rekodi rasmi zilizobadilishwa.`,
    };

    return {
      requestId: request.requestId,
      providerId: this.id,
      model: 'field-fussion-mock-v1',
      isSimulated: true,
      responseSource: 'simulated',
      simulatedNotice:
        'Simulated response generated by MockAiProvider in Free Development Mode — not generated by a real AI model.',
      advisoryText:
        advisoryByLang[request.context.preferredLanguage] ?? advisoryByLang.en,
      uncertaintyNote:
        'Simulated mock response for testing only — not live agronomic AI.',
      requiresApproval: Boolean(request.includeDraftSuggestion),
      privacyNotice:
        'Minimized context used (no email, phone, or private financial data).',
      usage: {
        latencyMs: 2,
        inputTokens: Math.ceil(request.prompt.length / 4),
        outputTokens: 42,
      },
    };
  }
}
